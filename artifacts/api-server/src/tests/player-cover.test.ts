import assert from "node:assert/strict";
import { createGameState, runBotTurnsIfNeeded } from "../lib/gameEngine.js";
import { recordMissedTurn, resetMissedTurns, returnCoveredSeat } from "../lib/playerCover.js";
import { serializeState } from "../routes/game.js";
let state = createGameState("cover-test", ["Sam", "Alex"], "online");
state = recordMissedTurn(state, "player_0", 1);
assert.equal(state.players[0].isBot, false);
assert.equal(state.players[0].consecutiveMissedTurns, 1);
const reset = resetMissedTurns(state, "player_0");
assert.equal(recordMissedTurn(reset, "player_0", 3).players[0].isBot, false);
assert.equal(recordMissedTurn(state, "player_0", 1), state, "one turn cannot count twice");
state = recordMissedTurn(state, "player_0", 3);
assert.equal(state.players[0].botCovering, true);
assert.equal(state.players[0].botSkillLevel, "medium");
assert.equal(state.players[0].name, "Sam");
assert.ok(state.log.includes("Sam missed two turns. A bot is covering for them."));
assert.ok(serializeState(state, 1).players[0].hand.every(c => c.id === "back"));
const returned = returnCoveredSeat(state, "player_0");
assert.equal(returned.players[0].isBot, false);
assert.equal(returned.players[0].consecutiveMissedTurns, 0);
assert.equal(runBotTurnsIfNeeded(returned), returned, "no bot runs after the current covered seat returns");
assert.ok(returned.log.includes("Sam is back."));
assert.equal(returnCoveredSeat({ ...state, players: state.players.map(p => ({ ...p, botCovering: false })) }, "player_0").players[0].isBot, true);
console.log("player-cover.test.ts: consecutive expiry reset, medium cover, privacy and immediate return passed");